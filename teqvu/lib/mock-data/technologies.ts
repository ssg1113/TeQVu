// Generates realistic sparkline data trending upward
function genSparkline(trend: 'up' | 'down' | 'flat' | 'volatile', base: number = 50): number[] {
  const points: number[] = [];
  let val = base;
  for (let i = 0; i < 7; i++) {
    if (trend === 'up') val += Math.random() * 8 - 1;
    else if (trend === 'down') val -= Math.random() * 6 + 1;
    else if (trend === 'flat') val += Math.random() * 4 - 2;
    else val += Math.random() * 20 - 10;
    points.push(Math.max(0, Math.round(val)));
  }
  return points;
}

