export function getTechBySlug(slug: string): Technology | undefined {
  return technologies.find(t => t.slug === slug);
}

export function getTechsByCategory(category: string): Technology[] {
  return technologies.filter(t => t.category === category);
}

export function getTrendingTechs(limit = 6): Technology[] {
  return [...technologies]
    .sort((a, b) => b.trendScore - a.trendScore)
    .slice(0, limit);
}

export function getEmergingTechs(limit = 5): Technology[] {
  return technologies
    .filter(t => t.status === 'emerging')
    .sort((a, b) => b.growth - a.growth)
    .slice(0, limit);
}

export function getFallingTechs(limit = 6): Technology[] {
  return technologies
    .filter(t => t.status === 'declining' || t.status === 'falling' || t.growth < 0)
    .sort((a, b) => a.growth - b.growth)
    .slice(0, limit);
}

